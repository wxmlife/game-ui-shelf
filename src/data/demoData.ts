import type { LibrarySnapshot, UiImage } from '../domain/models'

const createdAt = '2026-10-01T08:00:00.000Z'

function image(
  id: string,
  gameId: string,
  moduleKey: string,
  moduleName: string,
  title: string,
  sequenceOrder: number,
  tags: string[],
  options: Partial<UiImage> = {},
): UiImage {
  return {
    id,
    gameId,
    moduleId: `${gameId}-${moduleKey}`,
    moduleKey,
    moduleName,
    flowName: options.flowName,
    title,
    originalFilename: `${moduleKey}${moduleName}-${title}.png`,
    imageUrl: `/demo/${id}.svg`,
    thumbnailUrl: `/demo/${id}.svg`,
    width: 1170,
    height: 2532,
    sequenceOrder,
    tags,
    platform: options.platform ?? 'iOS',
    version: options.version ?? '1.8.0',
    createdAt,
    ...options,
  }
}

